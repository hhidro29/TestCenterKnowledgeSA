import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const OUTPUT = path.join(HERE, "bundled-data.mjs");

async function collectFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...await collectFiles(fullPath));
    } else if (entry.isFile()) {
      files.push(fullPath);
    }
  }
  return files;
}

const sourceFiles = [
  path.join(ROOT, "Prompt Sistem Chatbot - Knowledge Base Terstruktur.md"),
  ...await collectFiles(path.join(ROOT, "knowledge-base")),
];
const entries = {};
for (const filePath of sourceFiles.sort()) {
  const key = path.relative(ROOT, filePath).split(path.sep).join("/");
  entries[key] = await fs.readFile(filePath, "utf8");
}

const source = [
  "// Generated by prototype/generate-bundled-data.mjs. Edit the source files instead.",
  `const BUNDLED_FILES = Object.freeze(${JSON.stringify(entries)});`,
  "export { BUNDLED_FILES };",
  "",
].join("\n");
await fs.writeFile(OUTPUT, source);
console.log(`Bundled ${Object.keys(entries).length} files into ${path.relative(ROOT, OUTPUT)}`);
